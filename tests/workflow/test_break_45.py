def test_the_same_question_asked_again_after_the_orchestrator_answered_gets_no_other_answer(
    attachable: Workflow,
) -> None:
    attachable.add_pull_request(7)
    _record(attachable)
    question = _question(attachable, text=_DAILY)
    answer = {
        "id": 5,
        "body": f"{_ORCHESTRATOR}\n2",
        "created_at": "2026-10-19T18:05:00Z",
        "user": {"login": "example-owner"},
    }
    _comments(attachable, question, answer)
    _tick_at(attachable, 6)
    # The worker lost its context and asks the very same words again.
    again = {**question, "id": 9, "created_at": "2026-10-19T18:20:00Z"}
    _comments(attachable, question, answer, again)

    for minutes in (21, 36, 60):
        _tick_at(attachable, minutes)

    given = _answers(attachable)
    assert given == [] or all("answered for the owner: 2" in answer for answer in given), given


def test_three_workers_asking_at_once_get_one_answer_each(attachable: Workflow) -> None:
    (attachable.state / "permission-example-owner").write_text("write\n")
    for number in (7, 8, 9):
        attachable.add_pull_request(number)
        _record(attachable, number)
        comment = _comment(4 + number * 10, _DAILY)
        _comments(attachable, comment, number=number)

    for minutes in (15, 18, 30):
        _tick_at(attachable, minutes)

    for number in (7, 8, 9):
        pages = json.loads((attachable.state / f"comments-{number}.json").read_text())
        answers = [c for p in pages for c in p if str(c["body"]).startswith(_ORCHESTRATOR)]
        assert len(answers) == 1, (number, answers)
    logged = [line.split(" ", 1)[1] for line in _answered_in_log(attachable)]
    assert sorted(logged) == [f'answered for the owner: cloud-{n}, "1"' for n in (7, 8, 9)]


def test_two_ticks_at_once_post_one_answer(attachable: Workflow) -> None:
    _ask(attachable, _DAILY)
    # GitHub is slow to take the comment, so the two ticks overlap around it.
    real = attachable.bin / "gh"
    real.rename(attachable.bin / "gh-real")
    attachable.fake(
        "gh",
        "#!/bin/bash\n"
        '[[ "$*" != *" -X POST "* ]] || sleep 4\n'
        'exec "$(dirname "$0")/gh-real" "$@"\n',
    )
    env = {**attachable.env, **_ENV, "WORKFLOW_NOW": str(_NOW + 900)}
    tick = attachable.script.parent / "tick"
    ticks = [
        subprocess.Popen(
            ["bash", str(tick)],
            cwd=attachable.repo,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )
        for _ in range(2)
    ]
    for run in ticks:
        run.communicate(timeout=110)
    _tick_at(attachable, 18)

    assert len(_answers(attachable)) == 1
    assert len(_answered_in_log(attachable)) == 1


def test_a_post_that_github_keeps_but_that_hangs_past_the_timeout_is_noted_once(
    attachable: Workflow,
) -> None:
    _ask(attachable, _DAILY)
    real = attachable.bin / "gh"
    real.rename(attachable.bin / "gh-real")
    # GitHub keeps the comment, then the connection hangs past `call`'s 30 seconds.
    attachable.fake(
        "gh",
        "#!/bin/bash\n"
        'if [[ "$*" == *" -X POST "* && ! -e @STATE@/hung ]]; then\n'
        '  touch @STATE@/hung; "$(dirname "$0")/gh-real" "$@" >/dev/null; exec sleep 40\n'
        "fi\n"
        'exec "$(dirname "$0")/gh-real" "$@"\n',
    )
    attachable.run_script("tick", env={**_ENV, "WORKFLOW_NOW": str(_NOW + 900)})

    for minutes in (18, 21, 40):
        _tick_at(attachable, minutes)

    assert len(_answers(attachable)) == 1
    assert len(_answered_in_log(attachable)) == 1
    assert len(_wake_log(attachable)) == 1


def test_github_failing_on_the_second_read_answers_at_the_next_tick(attachable: Workflow) -> None:
    _ask(attachable, _DAILY)
    real = attachable.bin / "gh"
    real.rename(attachable.bin / "gh-real")
    # The first list of the comments goes through, the read just before posting fails once.
    attachable.fake(
        "gh",
        "#!/bin/bash\n"
        'if [[ "$*" == *"/comments?per_page=100"* ]]; then\n'
        "  n=$(cat @STATE@/reads 2>/dev/null || echo 0); echo $((n + 1)) > @STATE@/reads\n"
        '  [[ $n != 1 ]] || { echo "HTTP 502: Bad Gateway" >&2; exit 1; }\n'
        "fi\n"
        'exec "$(dirname "$0")/gh-real" "$@"\n',
    )
    attachable.run_script("tick", env={**_ENV, "WORKFLOW_NOW": str(_NOW + 900)})
    assert _answers(attachable) == []

    _tick_at(attachable, 18)
    _tick_at(attachable, 21)

    assert len(_answers(attachable)) == 1


def test_a_config_without_the_key_waits_the_default_15_minutes(attachable: Workflow) -> None:
    config = attachable.repo / "shipline.json"
    values = json.loads(config.read_text())
    values.pop("answer_for_owner_after_minutes", None)
    config.write_text(json.dumps(values))
    _ask(attachable, _DAILY)

    _tick_at(attachable, 14)
    assert _answers(attachable) == []
    _tick_at(attachable, 15)
    assert len(_answers(attachable)) == 1


def test_a_night_of_answers_is_listed_once_in_the_morning(attachable: Workflow) -> None:
    # Asked at 23:00; the check-in is read only in the day.
    _ask(attachable, _DAILY, at=_NOW + 5 * 3600)

    for minutes in (5 * 60 + 15, 7 * 60, 9 * 60 + 2, 15 * 60 + 2, 15 * 60 + 40):
        _tick_at(attachable, minutes)

    assert len(_answers(attachable)) == 1
    told = _told(attachable)
    assert len(told) == 1, told
    assert 'answered for the owner: cloud-7, "1" (23:15)' in told[0]


def test_a_worker_report_after_the_answer_does_not_bring_a_second_one(
    attachable: Workflow,
) -> None:
    _ask(attachable, _DAILY)
    _tick_at(attachable, 15)
    pages = json.loads((attachable.state / "comments-7.json").read_text())
    # The worker reads the answer, carries on, and later asks another question.
    carry_on = _comment(20, "Took 1; carrying on.", _NOW + 18 * 60)
    other = _comment(21, _DAILY.replace("retry setting", "timeout setting"), _NOW + 30 * 60)
    (attachable.state / "comments-7.json").write_text(json.dumps([pages[0] + [carry_on, other]]))

    for minutes in (20, 44, 46, 60):
        _tick_at(attachable, minutes)

    assert [a.split("\n", 1)[0] for a in _answers(attachable)] == [
        f"{_ORCHESTRATOR} answered for the owner: 1"
    ] * 2
    assert len(_answered_in_log(attachable)) == 2


def test_a_marked_comment_from_a_reader_does_not_open_a_question(attachable: Workflow) -> None:
    attachable.add_pull_request(7)
    _record(attachable)
    (attachable.state / "permission-passer-by").write_text("read\n")
    # A passer-by on the public pull request posts the worker's marker and a question.
    stranger = {**_question(attachable, text=_DAILY), "user": {"login": "passer-by"}}
    _comments(attachable, stranger)

    _tick_at(attachable, 60)

    assert _answers(attachable) == []
    assert not (attachable.state / "attached").exists()


