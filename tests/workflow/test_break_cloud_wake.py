def test_an_address_with_shell_text_runs_nothing(attachable: Workflow) -> None:
    attachable.add_pull_request(7)
    record = _record(attachable)
    pwned = attachable.state / "pwned"
    address = f"https://claude.ai/code/session_01X?a=$(touch${{IFS}}{pwned})`touch${{IFS}}{pwned}`"
    record.write_text(json.dumps({**json.loads(record.read_text()), "url": address}))

    _tick(attachable, 0)
    _tick(attachable, 30)

    assert not pwned.exists()
    assert (attachable.state / "attached").read_text().splitlines() == [address]


def test_a_client_that_ignores_the_hang_up_is_not_left_running(
    attachable: Workflow,
) -> None:
    """A client left behind holds memory on a machine shared by many sessions."""
    attachable.add_pull_request(7)
    _record(attachable)
    (attachable.state / "attach-deaf").touch()

    _tick(attachable, 0)
    _tick(attachable, 30, WORKFLOW_CLOUD_ATTACH_SECONDS="2")

    assert _pane_gone(attachable)
    pid = int((attachable.state / "deaf.pid").read_text())
    time.sleep(0.5)
    try:
        os.kill(pid, 0)
        alive = True
    except ProcessLookupError:
        alive = False
    assert not alive, "the attached client outlived its pane"


def test_a_tick_ended_mid_attach_leaves_no_pane_behind(attachable: Workflow) -> None:
    """The tick's Python is ended while it waits for the box; nothing retries that wake."""
    attachable.add_pull_request(7)
    _record(attachable)
    _tick(attachable, 0)
    no_box = attachable.state / "no-box"
    no_box.touch()
    attachable.fake(
        "claude",
        _ATTACHED_CLAUDE.replace(
            'if [ -e "@STATE@/attach-deaf" ]; then',
            'if [ -e "@STATE@/no-box" ]; then exec /bin/sleep 600; fi\n'
            '  if [ -e "@STATE@/attach-deaf" ]; then',
        ),
    )
    env = {**attachable.env, **_ENV, "WORKFLOW_NOW": str(_NOW + 1800)}
    tick = subprocess.Popen(
        ["bash", str(attachable.script.parent / "tick")],
        cwd=attachable.repo,
        env=env,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    deadline = time.monotonic() + 60
    while _pane_gone(attachable) and time.monotonic() < deadline:
        time.sleep(0.2)
    assert not _pane_gone(attachable), "the wake never started its pane"
    subprocess.run(
        ["pkill", "-TERM", "-f", f"cloud_workers.py wake {attachable.repo} "],
        check=False,
    )
    tick.wait(timeout=60)
    no_box.unlink()

    for minutes in (33, 61, 64):
        _tick(attachable, minutes)

    assert _pane_gone(attachable), (
        "a pane of an ended tick is left until the next stretch"
    )


def test_an_outsiders_marked_comment_does_not_hold_the_wake(
    attachable: Workflow,
) -> None:
    """Anyone may comment on a public pull request; only the worker's account reports."""
    attachable.add_pull_request(7)
    _record(attachable)
    (attachable.state / "permission-example-outsider").write_text("read\n")
    _tick(attachable, 0)
    fake = _reply(
        4,
        f"{_MARKER}\nWhich option should I take? Reply `a` or `b`.",
        5,
        login="example-outsider",
    )
    _comments(attachable, fake)

    for minutes in (6, 36, 66, 96):
        _tick(attachable, minutes)

    assert _typed(attachable) == [f"{_url(7)}\t{_STATUS}"]
