def test_two_quiet_workers_in_one_tick_are_both_woken_and_leave_no_pane(
    attachable: Workflow,
) -> None:
    for number in (7, 8):
        attachable.add_pull_request(number)
        _record(attachable, number)
    _tick(attachable, 0)

    _tick(attachable, 30)

    assert sorted(_typed(attachable)) == [
        f"{_url(7)}\t{_STATUS}",
        f"{_url(8)}\t{_STATUS}",
    ]
    assert _pane_gone(attachable, 7)
    assert _pane_gone(attachable, 8)


