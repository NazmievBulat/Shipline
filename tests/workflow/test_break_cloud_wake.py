_NOW = 1792432800
_ENV = {"WORKFLOW_NOW": str(_NOW), "TZ": "UTC"}
_MARKER = "<!-- cloud-worker -->"
_SIGNED = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
_TMUX = shutil.which("tmux")


def _url(number: int) -> str:
    return f"https://claude.ai/code/session_01Example{number}?from=cli&m=0"


_STATUS = (
    "Status check: nothing has been pushed or reported for 30 minutes. If your question was "
    "answered, carry on; if something blocks you, report it as a question and carry on with "
    "what it does not block; never end your turn to wait."
)


def _answered(number: int) -> str:
    return (
        f"Your question on pull request {number} was answered in its comments. Read the answer "
        "and carry on."
    )


# A cloud session as `claude --cloud <address>` shows it, recording what is typed into it.
# `attach-limit-hint`: the usage limit line with the hint Claude prints under it.
# `attach-deaf`: a client that ignores the hang-up and never draws a box.
_ATTACHED_CLAUDE = r"""#!/bin/bash
if [[ $# == 2 && $1 == --cloud ]]; then
  echo "$2" >> "@STATE@/attached"
  if [ -e "@STATE@/attach-deaf" ]; then
    trap '' HUP
    echo $$ > "@STATE@/deaf.pid"
    exec /bin/sleep 600
  fi
  rule=$(printf '─%.0s' {1..60})
  draw() {
    printf '\033[H\033[2J● Working on the ticket.\n'
    if [ -e "@STATE@/attach-limit-hint" ]; then
      printf "  ⎿  You've hit your limit · resets 4pm (UTC)\n"
      printf "     /upgrade to increase your usage limit.\n"
    fi
    printf '\n%s\n> \0337\n\n\n%s\n  ? for shortcuts\0338' "$rule" "$rule"
  }
  draw
  while IFS= read -r line; do
    printf '%s\t%s\n' "$2" "$line" >> "@STATE@/typed"
    draw
  done
  exit 0
fi
exec "@STATE@/../claude-harness" "$@"
"""


@pytest.fixture
def attachable(workflow: Workflow) -> Iterator[Workflow]:
    if _TMUX is None:
        pytest.skip("tmux is not installed")  # noqa: TID251
    sockets = Path(tempfile.mkdtemp(prefix="wb-"))
    (workflow.bin / "tmux").unlink()
    (workflow.bin / "claude").rename(workflow.root / "claude-harness")
    workflow.fake("claude", _ATTACHED_CLAUDE)
    workflow.env["TMUX_TMPDIR"] = str(sockets)
    workflow.orchestrator("busy")
    try:
        yield workflow
    finally:
        for number in (7, 8):
            subprocess.run(
                [_TMUX, "-L", f"wake-cloud-{number}", "kill-server"],
                env=workflow.env,
                capture_output=True,
                check=False,
            )
        pid = workflow.state / "deaf.pid"
        if pid.exists():
            try:
                os.kill(int(pid.read_text()), signal.SIGKILL)
            except ProcessLookupError:
                pass
        shutil.rmtree(sockets, ignore_errors=True)


def _record(workflow: Workflow, number: int = 7) -> Path:
    notes = workflow.repo / ".local/workflow"
    notes.mkdir(parents=True, exist_ok=True)
    record = notes / f"cloud-{number}"
    record.write_text(
        json.dumps(
            {
                "url": _url(number),
                "started_at": _NOW,
                "status": "working",
                "last_comment_id": 0,
                "last_comment_at": None,
            }
        )
    )
    return record


def _at(minutes: int) -> str:
    return datetime.fromtimestamp(_NOW + minutes * 60, UTC).strftime(
        "%Y-%m-%dT%H:%M:%SZ"
    )


def _report(identity: int, text: str, minutes: int) -> dict[str, object]:
    """A worker's report, posted from the owner's account through the connector, signed."""
    return {
        "id": identity,
        "body": f"{_MARKER}\n{text}{_SIGNED}",
        "created_at": _at(minutes),
        "user": {"login": "example-owner"},
        "html_url": f"https://github.com/example-org/example-app/pull/7#issuecomment-{identity}",
    }


def _reply(
    identity: int, body: str, minutes: int, login: str = "example-owner"
) -> dict:
    return {
        "id": identity,
        "body": body,
        "created_at": _at(minutes),
        "user": {"login": login},
    }


def _comments(
    workflow: Workflow, *comments: dict[str, object], number: int = 7
) -> None:
    (workflow.state / f"comments-{number}.json").write_text(
        json.dumps([list(comments)])
    )


def _tick(workflow: Workflow, minutes: int, **env: str) -> None:
    done = workflow.run_script(
        "tick", env={**_ENV, "WORKFLOW_NOW": str(_NOW + minutes * 60), **env}
    )
    assert done.returncode == 0, done.stderr


def _typed(workflow: Workflow) -> list[str]:
    path = workflow.state / "typed"
    return path.read_text().splitlines() if path.exists() else []


def _stuck(workflow: Workflow, number: int = 7) -> list[str]:
    return [
        message for message in workflow.sent() if f"stuck? cloud-{number}" in message
    ]


def _log(workflow: Workflow) -> list[str]:
    log = workflow.wake_log
    lines = log.read_text().splitlines() if log.exists() else []
    return [
        line
        for line in lines
        if re.fullmatch(r"[0-9]+ (woke cloud-.*|cloud-[0-9]+ wake failed: .*)", line)
    ]


def _pane_gone(workflow: Workflow, number: int = 7) -> bool:
    assert _TMUX is not None
    asked = subprocess.run(
        [
            _TMUX,
            "-L",
            f"wake-cloud-{number}",
            "has-session",
            "-t",
            f"=wake-cloud-{number}",
        ],
        env=workflow.env,
        capture_output=True,
        check=False,
    )
    return asked.returncode != 0


def _owner_writes(workflow: Workflow) -> None:
    (workflow.state / "permission-example-owner").write_text("admin\n")


def test_a_worker_quiet_after_its_first_push_is_woken_once_then_named_once(
    attachable: Workflow,
) -> None:
    """The daily flow: reports relayed every 3 minutes, then the worker stops saying nothing."""
    attachable.add_pull_request(7)
    _record(attachable)
    _comments(attachable, _report(4, "Started.", 1), _report(5, "First push.", 5))
    attachable.push_from_elsewhere(7)
    for minutes in (0, 6, 33):
        _tick(attachable, minutes)
    assert _typed(attachable) == []

    _tick(attachable, 36)
    assert _typed(attachable) == [f"{_url(7)}\t{_STATUS}"]
    assert _pane_gone(attachable)
    for minutes in (39, 63, 66, 69, 99):
        _tick(attachable, minutes)

    assert _typed(attachable) == [f"{_url(7)}\t{_STATUS}"]
    assert len(_stuck(attachable)) == 1


@pytest.mark.parametrize(
    "body",
    [
        "<!-- shipline-orchestrator -->\nTake the first option.",
        "Take the first option.",
    ],
    ids=["orchestrator", "owner-from-phone"],
)
def test_an_answer_the_worker_never_saw_wakes_it_at_the_next_tick(
    attachable: Workflow, body: str
) -> None:
    attachable.add_pull_request(7)
    _record(attachable)
    _owner_writes(attachable)
    question = _report(4, "Which option should I take? Reply `first` or `second`.", 3)
    _comments(attachable, question)
    for minutes in (3, 33, 63):
        _tick(attachable, minutes)
    assert _typed(attachable) == []

    _comments(attachable, question, _reply(5, body, 64))
    _tick(attachable, 66)

    assert _typed(attachable) == [f"{_url(7)}\t{_answered(7)}"]
    assert not (attachable.repo / ".local/workflow/cloud-7.asking").exists()
    assert _pane_gone(attachable)


def test_the_owners_quote_reply_from_the_phone_is_an_answer(
    attachable: Workflow,
) -> None:
    """GitHub's "Quote reply" copies the quoted comment's text, its connector line included."""
    attachable.add_pull_request(7)
    _record(attachable)
    _owner_writes(attachable)
    question = _report(4, "Which option should I take? Reply `first` or `second`.", 3)
    _comments(attachable, question)
    _tick(attachable, 3)
    quoted = (
        "> Which option should I take? Reply `first` or `second`.\n"
        "> \n"
        "> ---\n"
        "> _Generated by [Claude Code](https://claude.ai/code)_\n"
        "\n"
        "first"
    )
    _comments(attachable, question, _reply(5, quoted, 10))

    for minutes in (12, 42, 72, 102):
        _tick(attachable, minutes)

    seen = {
        "typed": _typed(attachable),
        "still asking the owner": (
            attachable.repo / ".local/workflow/cloud-7.asking"
        ).exists(),
        "named stuck": len(_stuck(attachable)),
    }
    assert seen == {
        "typed": [f"{_url(7)}\t{_answered(7)}"],
        "still asking the owner": False,
        "named stuck": 0,
    }


def test_a_question_answered_and_acknowledged_in_one_tick_is_not_woken(
    attachable: Workflow,
) -> None:
    """The worker polls and saw the answer: its next report comes before the tick's wake."""
    attachable.add_pull_request(7)
    _record(attachable)
    _owner_writes(attachable)
    _comments(
        attachable,
        _report(4, "Which option should I take? Reply `first` or `second`.", 3),
        _reply(5, "<!-- shipline-orchestrator -->\nfirst", 5),
        _report(6, "Carrying on with the first option.", 7),
    )

    _tick(attachable, 0)
    _tick(attachable, 9)
    assert _typed(attachable) == []
    _tick(attachable, 37)

    assert _typed(attachable) == [f"{_url(7)}\t{_STATUS}"]


